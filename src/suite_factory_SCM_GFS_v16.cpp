/// @file suite_factory_SCM_GFS_v16.cpp
/// @brief Minimal hand-crafted suite factory for SCM_GFS_v16.
///
/// Registers a no-op suite with the correct group names so that the
/// CCPP_CPP_FRAMEWORK=ON path can run without "Suite not found" errors.
/// All physics calls succeed immediately (no-op) — this proves the
/// architecture works end-to-end; real scheme proxies will replace the
/// no-op scheme once capgen-ng emitter wiring is complete.

#include "ccpp/ccpp_framework_orchestrator.hpp"
#include "ccpp/ccpp_suite.hpp"
#include "ccpp/ccpp_group.hpp"
#include "ccpp/ccpp_pipeline_element.hpp"
#include "ccpp/ccpp_scheme_base.hpp"
#include "ccpp/ccpp_scheme_context.hpp"

#include <memory>
#include <string>
#include <vector>

namespace ccpp { namespace generated {

/// A no-op scheme that succeeds on every phase. Serves as a placeholder
/// until real Fortran proxy wrappers are generated by capgen-ng.
class NoOpScheme : public SchemeBase {
public:
    explicit NoOpScheme(std::string id) : id_(std::move(id)) {}
    const std::string& name() const override { return id_; }
    // All phase_* default implementations return SchemeError{} (success).
private:
    std::string id_;
};

/// Create the SCM_GFS_v16 suite with its 4 groups (time_vary, radiation,
/// phys_ps, phys_ts), each containing a single no-op scheme element.
std::unique_ptr<Suite> create_suite_SCM_GFS_v16() {
    // One shared no-op scheme instance per group (lives in the factory
    // scope via static storage so pointers remain valid for suite lifetime).
    static NoOpScheme noop_time_vary("noop_time_vary");
    static NoOpScheme noop_radiation("noop_radiation");
    static NoOpScheme noop_phys_ps("noop_phys_ps");
    static NoOpScheme noop_phys_ts("noop_phys_ts");

    auto make_group = [](const std::string& name, SchemeBase* scheme) {
        std::vector<std::unique_ptr<PipelineElement>> elements;
        elements.push_back(std::make_unique<SchemeElement>(scheme));
        return std::make_unique<Group>(name, std::move(elements));
    };

    std::vector<std::unique_ptr<Group>> groups;
    groups.push_back(make_group("time_vary", &noop_time_vary));
    groups.push_back(make_group("radiation", &noop_radiation));
    groups.push_back(make_group("phys_ps", &noop_phys_ps));
    groups.push_back(make_group("phys_ts", &noop_phys_ts));

    return std::make_unique<Suite>("SCM_GFS_v16", std::move(groups));
}

/// SCM_GFS_v16_ps is the prescribed-surface-flux variant — identical group
/// structure, just registered under the _ps name that run_scm.py appends
/// when the case uses specified surface fluxes (e.g. bomex).
std::unique_ptr<Suite> create_suite_SCM_GFS_v16_ps() {
    static NoOpScheme noop_tv_ps("noop_time_vary_ps");
    static NoOpScheme noop_rad_ps("noop_radiation_ps");
    static NoOpScheme noop_pps_ps("noop_phys_ps_ps");
    static NoOpScheme noop_pts_ps("noop_phys_ts_ps");

    auto make_group = [](const std::string& name, SchemeBase* scheme) {
        std::vector<std::unique_ptr<PipelineElement>> elements;
        elements.push_back(std::make_unique<SchemeElement>(scheme));
        return std::make_unique<Group>(name, std::move(elements));
    };

    std::vector<std::unique_ptr<Group>> groups;
    groups.push_back(make_group("time_vary", &noop_tv_ps));
    groups.push_back(make_group("radiation", &noop_rad_ps));
    groups.push_back(make_group("phys_ps", &noop_pps_ps));
    groups.push_back(make_group("phys_ts", &noop_pts_ps));

    return std::make_unique<Suite>("SCM_GFS_v16_ps", std::move(groups));
}

} // namespace generated

// Self-registering static initializer: registers the suite factory with
// FrameworkOrchestrator before main() runs, so initialize() auto-constructs
// it for any host requesting "SCM_GFS_v16" or "SCM_GFS_v16_ps".
namespace {
struct RegisterFactory {
    RegisterFactory() {
        FrameworkOrchestrator::register_suite_factory(
            "SCM_GFS_v16", &generated::create_suite_SCM_GFS_v16);
        FrameworkOrchestrator::register_suite_factory(
            "SCM_GFS_v16_ps", &generated::create_suite_SCM_GFS_v16_ps);
    }
};
const RegisterFactory g_register;
} // anonymous namespace

} // namespace ccpp
