"""Fortran bind(C) shim emitter for group cap subroutines.

For each group+phase combination in a resolved suite, this module emits a
thin Fortran bind(C) wrapper subroutine that:
  1. Receives C-compatible arguments (integers by value, char* + len for errmsg)
  2. Converts the C char buffer to a Fortran character variable
  3. Calls the corresponding generated Fortran group cap subroutine
  4. Copies the output errmsg back to the C buffer

The emitted shims allow the C++ orchestrator (via extern "C" declarations)
to call the real Fortran physics group caps without any per-scheme bind(C)
wrappers — one shim per group+phase is sufficient since the group cap
already handles all per-scheme argument marshalling internally.

This works for ANY suite, not just SCM_GFS_v16 — the emitter is driven
by the suite resolution's group names and phase lists.
"""

from __future__ import annotations

import os
from typing import List, Optional, TYPE_CHECKING

if TYPE_CHECKING:
    from generator.suite_resolver import SuiteResolution

#: All physics phases that group caps implement.
_PHASES = ("init", "timestep_init", "run", "timestep_final", "final")

#: Maximum error message length (must match C++ side ERRMSG_LEN).
_ERRMSG_LEN = 512


def _shim_symbol(suite_name: str, group_name: str, phase: str) -> str:
    """Return the C-linkage symbol name for a group+phase shim.

    Convention: ccpp_<suite>_<group>_<phase>_c (all lowercase).
    This is what the C++ proxy will declare as extern "C".
    """
    return "ccpp_{}_{}_{}_c".format(
        suite_name.lower(), group_name.lower(), phase.lower()
    )


def _emit_one_shim(
    suite_name: str,
    group_name: str,
    phase: str,
) -> List[str]:
    """Emit Fortran source lines for one bind(C) shim subroutine."""
    symbol = _shim_symbol(suite_name, group_name, phase)
    cap_module = "ccpp_{}_{}_cap".format(suite_name, group_name)
    cap_sub = "{}_{}".format(group_name, phase)

    lines: List[str] = []
    lines.append("  subroutine {}(lb, ub, nphys_threads, errmsg_c, errmsg_len, errflg) &".format(symbol))
    lines.append("      bind(C, name=\"{}\")".format(symbol))
    lines.append("    use iso_c_binding")
    lines.append("    use {}, only: {}".format(cap_module, cap_sub))
    lines.append("    integer(c_int), value, intent(in) :: lb")
    lines.append("    integer(c_int), value, intent(in) :: ub")
    lines.append("    integer(c_int), value, intent(in) :: nphys_threads")
    lines.append("    character(c_char), intent(inout) :: errmsg_c(*)")
    lines.append("    integer(c_int), value, intent(in) :: errmsg_len")
    lines.append("    integer(c_int), intent(out) :: errflg")
    lines.append("")
    lines.append("    character(len={}) :: f_errmsg".format(_ERRMSG_LEN))
    lines.append("    integer :: i")
    lines.append("")
    lines.append("    f_errmsg = ''")
    lines.append("    call {}(lb=int(lb), ub=int(ub), &".format(cap_sub))
    lines.append("             nphys_threads=int(nphys_threads), &")
    lines.append("             errmsg=f_errmsg, errflg=errflg)")
    lines.append("")
    lines.append("    ! Copy Fortran error message back to C buffer")
    lines.append("    do i = 1, min(len_trim(f_errmsg), int(errmsg_len) - 1)")
    lines.append("      errmsg_c(i) = f_errmsg(i:i)")
    lines.append("    end do")
    lines.append("    if (i <= int(errmsg_len)) errmsg_c(i) = c_null_char")
    lines.append("")
    lines.append("  end subroutine {}".format(symbol))
    return lines


def emit_group_shims(
    suite_name: str,
    group_names: List[str],
    output_dir: str,
    phases: Optional[List[str]] = None,
) -> str:
    """Emit a single Fortran source file containing bind(C) shims for all
    group+phase combinations in a suite.

    Parameters
    ----------
    suite_name : str
        Suite name (e.g., "SCM_GFS_v16").
    group_names : list of str
        Group names from the suite (e.g., ["time_vary", "radiation", ...]).
    output_dir : str
        Directory where the .F90 file is written.
    phases : list of str, optional
        Phases to emit shims for. Defaults to all 5 physics phases.

    Returns
    -------
    str
        Path to the written .F90 file.
    """
    if phases is None:
        phases = list(_PHASES)

    filename = "ccpp_{}_group_shims.F90".format(suite_name.lower())
    filepath = os.path.join(output_dir, filename)
    os.makedirs(output_dir, exist_ok=True)

    lines: List[str] = []
    lines.append("! Auto-generated bind(C) shims for {} group caps".format(suite_name))
    lines.append("! DO NOT EDIT — regenerated by capgen --emit-cpp")
    lines.append("")
    lines.append("module ccpp_{}_group_shims".format(suite_name.lower()))
    lines.append("  use iso_c_binding")
    lines.append("  implicit none")
    lines.append("  private")
    lines.append("")
    lines.append("contains")
    lines.append("")

    for group_name in group_names:
        for phase in phases:
            shim_lines = _emit_one_shim(suite_name, group_name, phase)
            lines.extend(shim_lines)
            lines.append("")

    lines.append("end module ccpp_{}_group_shims".format(suite_name.lower()))

    with open(filepath, "w") as f:
        f.write("\n".join(lines) + "\n")
    return filepath


def emit_group_shims_from_resolution(
    suite_resolution: "SuiteResolution",
    output_dir: str,
) -> str:
    """Convenience: emit group shims directly from a SuiteResolution object."""
    group_names = [rg.group_name for rg in suite_resolution.groups]
    return emit_group_shims(
        suite_name=suite_resolution.suite_name,
        group_names=group_names,
        output_dir=output_dir,
    )
