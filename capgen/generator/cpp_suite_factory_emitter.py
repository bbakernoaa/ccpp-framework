"""C++ suite factory emitter using group-level bind(C) shims.

For each suite, emits a suite_factory_<suite>.cpp that:
  - Declares extern "C" functions matching the Fortran bind(C) shims
  - Implements one GroupCapScheme class per group (calls the group shim
    for whatever phase the pipeline dispatches)
  - Constructs a Suite with one Group per SDF group, each containing
    a single SchemeElement wrapping the GroupCapScheme
  - Self-registers with FrameworkOrchestrator via static initializer

This gives a real physics execution path: C++ dispatch overhead is
measured by the orchestrator→suite→group→element chain, then the
actual physics is executed by the existing generated Fortran group caps.
"""

from __future__ import annotations

import os
from typing import List, Optional, TYPE_CHECKING

if TYPE_CHECKING:
    from generator.suite_resolver import SuiteResolution

from generator.group_shim_emitter import _shim_symbol, _PHASES, _ERRMSG_LEN


def _emit_suite_factory_with_shims(
    suite_name: str,
    group_names: List[str],
) -> List[str]:
    """Build C++ source lines for a suite factory that calls group shims."""
    lines: List[str] = []

    lines.append("// Auto-generated suite factory for '{}' (group-cap dispatch)".format(suite_name))
    lines.append("// DO NOT EDIT — regenerated by capgen --emit-cpp")
    lines.append("")
    lines.append("#include <memory>")
    lines.append("#include <string>")
    lines.append("#include <cstring>")
    lines.append("#include <vector>")
    lines.append("")
    lines.append('#include "ccpp/ccpp_framework_orchestrator.hpp"')
    lines.append('#include "ccpp/ccpp_suite.hpp"')
    lines.append('#include "ccpp/ccpp_group.hpp"')
    lines.append('#include "ccpp/ccpp_pipeline_element.hpp"')
    lines.append('#include "ccpp/ccpp_scheme_base.hpp"')
    lines.append('#include "ccpp/ccpp_scheme_context.hpp"')
    lines.append("")

    # Extern "C" declarations for all group+phase shims
    lines.append('extern "C" {')
    for group_name in group_names:
        for phase in _PHASES:
            symbol = _shim_symbol(suite_name, group_name, phase)
            lines.append("void {}(int lb, int ub, int nphys_threads, "
                         "char* errmsg, int errmsg_len, int* errflg);".format(symbol))
    lines.append('} // extern "C"')
    lines.append("")

    lines.append("namespace ccpp { namespace generated {")
    lines.append("")

    # One GroupCapScheme class per group
    for group_name in group_names:
        class_name = "GroupCapScheme_{}_{}".format(suite_name, group_name)
        lines.append("/// Dispatches to the Fortran group cap for '{}'.".format(group_name))
        lines.append("class {} : public SchemeBase {{".format(class_name))
        lines.append("public:")
        lines.append("    const std::string& name() const override {")
        lines.append('        static const std::string n = "{}";'.format(group_name))
        lines.append("        return n;")
        lines.append("    }")
        lines.append("")

        # Each phase method calls the corresponding shim
        phase_method_map = {
            "init": "phase_init",
            "timestep_init": "phase_timestep_init",
            "run": "phase_run",
            "timestep_final": "phase_timestep_final",
            "final": "phase_final",
        }
        for phase, method in phase_method_map.items():
            symbol = _shim_symbol(suite_name, group_name, phase)
            lines.append("    SchemeError {}(SchemeContext& ctx) override {{".format(method))
            lines.append("        char errmsg[{}] = {{}};".format(_ERRMSG_LEN))
            lines.append("        int errflg = 0;")
            lines.append("        {}(ctx.col_start, ctx.col_end, 1, errmsg, {}, &errflg);".format(
                symbol, _ERRMSG_LEN))
            lines.append("        if (errflg != 0) {")
            lines.append("            SchemeError e; e.code = errflg; e.message = std::string(errmsg);")
            lines.append("            return e;")
            lines.append("        }")
            lines.append("        return SchemeError{};")
            lines.append("    }")
            lines.append("")

        lines.append("};")
        lines.append("")

    # Factory function
    lines.append("std::unique_ptr<Suite> create_suite_{}() {{".format(suite_name))
    for group_name in group_names:
        class_name = "GroupCapScheme_{}_{}".format(suite_name, group_name)
        lines.append("    static {} scheme_{};".format(class_name, group_name))
    lines.append("")
    lines.append("    std::vector<std::unique_ptr<Group>> groups;")

    for group_name in group_names:
        lines.append("    {")
        lines.append("        std::vector<std::unique_ptr<PipelineElement>> elements;")
        lines.append("        elements.push_back(std::make_unique<SchemeElement>(&scheme_{}));".format(
            group_name))
        lines.append('        groups.push_back(std::make_unique<Group>("{}", std::move(elements)));'.format(
            group_name))
        lines.append("    }")

    lines.append('    return std::make_unique<Suite>("{}", std::move(groups));'.format(suite_name))
    lines.append("}")
    lines.append("")
    lines.append("}} // namespace ccpp::generated")
    lines.append("")

    # Self-registering static initializer
    lines.append("namespace {")
    lines.append("struct Register_{} {{".format(suite_name))
    lines.append("    Register_{}() {{".format(suite_name))
    lines.append('        ccpp::FrameworkOrchestrator::register_suite_factory(')
    lines.append('            "{}", &ccpp::generated::create_suite_{});'.format(
        suite_name, suite_name))
    lines.append("    }")
    lines.append("};")
    lines.append("const Register_{0} g_register_{0};".format(suite_name))
    lines.append("} // anonymous namespace")

    return lines


def emit_suite_factory_with_shims(
    suite_name: str,
    group_names: List[str],
    output_dir: str,
) -> str:
    """Emit a suite factory .cpp file that dispatches to group cap shims.

    Parameters
    ----------
    suite_name : str
        Suite name (e.g., "SCM_GFS_v16").
    group_names : list of str
        Group names from the suite.
    output_dir : str
        Directory where the .cpp file is written.

    Returns
    -------
    str
        Path to the written .cpp file.
    """
    lines = _emit_suite_factory_with_shims(suite_name, group_names)
    filename = "suite_factory_{}.cpp".format(suite_name.lower())
    filepath = os.path.join(output_dir, filename)
    os.makedirs(output_dir, exist_ok=True)
    with open(filepath, "w") as f:
        f.write("\n".join(lines) + "\n")
    return filepath


def emit_suite_factory_from_resolution(
    suite_resolution: "SuiteResolution",
    output_dir: str,
) -> str:
    """Convenience: emit factory from a SuiteResolution object."""
    group_names = [rg.group_name for rg in suite_resolution.groups]
    return emit_suite_factory_with_shims(
        suite_name=suite_resolution.suite_name,
        group_names=group_names,
        output_dir=output_dir,
    )
